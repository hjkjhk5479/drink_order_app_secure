insert into public.stores (name)
select '測試飲料店'
where not exists (
  select 1 from public.stores where name = '測試飲料店'
);

insert into public.products (store_id, name, price)
select s.id, v.name, v.price
from public.stores s
cross join (
  values
    ('熟成紅茶', 35),
    ('春芽冷露', 35),
    ('白玉歐蕾', 60),
    ('胭脂多多', 50)
) as v(name, price)
where s.name = '測試飲料店'
and not exists (
  select 1 from public.products p
  where p.store_id = s.id and p.name = v.name
);

insert into public.toppings (store_id, name, price)
select s.id, v.name, v.price
from public.stores s
cross join (
  values
    ('白玉', 10),
    ('珍珠', 10),
    ('椰果', 10)
) as v(name, price)
where s.name = '測試飲料店'
and not exists (
  select 1 from public.toppings t
  where t.store_id = s.id and t.name = v.name
);
